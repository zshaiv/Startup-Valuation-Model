import streamlit as st
from predict import predict_valuation

st.set_page_config(
    page_title="Startup Valuation Predictor",
    page_icon="🚀",
    layout="centered"
)

st.title("🚀 Startup Valuation Prediction Model")

st.write(
    "Predict the estimated valuation of a startup "
    "using machine learning."
)

st.divider()

st.header("Enter Startup Details")

raised_amount_usd = st.number_input(
    "Amount Raised (USD)",
    min_value=0.0,
    value=5000000.0,
    step=100000.0
)

company_age = st.number_input(
    "Company Age (Years)",
    min_value=0.0,
    value=3.0,
    step=1.0
)

relationships = st.number_input(
    "Number of Relationships",
    min_value=0,
    value=10,
    step=1
)

funding_round_type = st.selectbox(
    "Funding Round Type",
    ["venture", "seed", "angel", "private_equity"]
)

funding_round_code = st.selectbox(
    "Funding Round",
    ["A", "B", "C", "D", "E", "F", "G"]
)

category_code = st.selectbox(
    "Startup Industry",
    ["software", "web", "mobile", "enterprise", "biotech", "other"]
)

country_code = st.selectbox(
    "Country",
    ["USA", "GBR", "IND", "CAN", "DEU", "other"]
)

st.divider()

if st.button("Predict Valuation", type="primary"):

    valuation = predict_valuation(
        raised_amount_usd=raised_amount_usd,
        company_age=company_age,
        relationships=relationships,
        funding_round_type=funding_round_type,
        funding_round_code=funding_round_code,
        category_code=category_code,
        country_code=country_code
    )

    st.success("Prediction Completed!")

    st.metric(
        label="Estimated Startup Valuation",
        value=f"${valuation:,.2f}"
    )

    st.caption(
        "This estimate is generated by a machine learning model "
        "and should not be treated as financial advice."
    )
